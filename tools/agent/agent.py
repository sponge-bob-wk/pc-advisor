def _too_thin(text, user_text):
    """回答太短、太敷衍 —— 用户问了一句，只得到"库里没有"五个字。

    实测 2026-11-11 演示走查：
      U「这机器保修几年」
      A「库里没有这项数据。」          ← 7 个字，等于什么都没说
    这句话**没有编造**，所以 _warranty_stretch / _tangent 全部放行，
    但它对用户毫无用处：没告诉他这台有什么服务承诺、也没告诉他该去哪儿问。

    判据：长度 < 16 字，且只有"没有/不知道/不清楚"这类否信息，没有一个具体名词。
    只在这种"又短又空"时才打回，不误伤"这台是 16G 内存"这种正常短答。

    ⚠️ 只有这一条不够（2026-11-11 演示彩排实测）：
      A「库里没有这项数据。这台机器提供「一年上门保修」服务。」
    28 个字，含"保修"，本条判据全部放行 —— 但用户拿这句话**什么也做不了**：
    还是不知道保修几年，也不知道该问谁。缺的不是长度，是**着落**。
    ⇒ 另加 _no_landing()，两条判据各管一件事，互不替代。
    """
    t = (text or "").strip()
    if len(t) >= 16:
        return False
    has_neg = any(w in t for w in ["没有", "没记", "不知道", "不清楚", "查不到",
                                   "无数据", "没有数据", "无法"])
    if not has_neg:
        return False
    # 有没有给出任何具体信息（型号/配置/年份/数字）
    has_info = bool(re.search(r"\d", t)) or any(
        w in t for w in ["保修", "售后", "网点", "客服", "上门", "条款", "详情页"])
    return not has_info


def _no_landing(text, user_text):
    """说了"库里没有"，但没告诉用户**接下来该怎么办**。

    实测 2026-11-11 演示彩排：
      U「这机器保修几年」（问的是年限，库里只有"一年上门保修"这项**服务**）
      A「库里没有这项数据。这台机器提供「一年上门保修」服务。」
    —— 28 个字，不编造、不跑题、也念了服务，前面三条判据全放行。
    但它把问题原样退回给用户了：那到底几年？我去哪儿问？

    本产品的立场是「没有数据也要给个着落」：说清楚这台有什么承诺、
    这个数只有谁能定、以及去哪个页面／问谁。这三样都不需要编数字。

    判据（两条同时成立才打回）：
      ① 回答里有"库里没有/查不到"这类否信息
      ② 全篇没有任何一个**可执行的出口**（详情页/客服/条款/官网/下单页/问厂商）
    只命中①不打回 —— 「库里没有返修率数据，但网点覆盖还算广」是合格回答。

    ⚠️ "出口"必须是**能去查的地方**，不能是描述。
    第一版把 `售后网点` 也算出口，结果这条判据放行了
      「库里没有返修率数据，但这个牌子售后网点覆盖还算广。」
    —— "网点覆盖广"是描述，不是"去哪儿查返修率"，用户照样没着落。
    ⇒ 去掉 `售后网点`，只留 `售后政策 / 售后条款`（这两个是能被查的东西）。
    """
    t = (text or "").strip()
    if not t:
        return False
    neg = re.search(r"库里(没有|没记|查不到)|没有(这项|该项)?数据|无法确定|不确定", t)
    if not neg:
        return False
    landing = re.search(
        r"详情页|商品页|下单页|客服|保修卡|发票|说明书|官网|官方网站"
        r"|售后(政策|条款)|问(一下)?(厂商|卖家|店家|客服)|咨询(厂商|客服|卖家)", t)
    return not landing


# 「开放式提问」—— 用户问的是"怎么样"，期望一段话，不是一个字段。
# 「保修几年」「多重」这类是封闭式（问一个具体值），一句话答完就算合格。
OPEN_ENDED = ["怎么样", "好不好", "如何", "值不值", "行不行", "怎么样啊",
              "推荐吗", "值得买吗", "评价", "讲讲", "说说", "介绍一下"]


def _too_brief(text, user_text):
    """用户问开放式问题，回答只有一句话 —— 信息没错，但答不动。

    实测 2026-11-11 演示彩排：
      U「屏幕怎么样」（开放式，期望听两句）
      A「屏幕素质在同价位不算突出。」            ← 13 个字，就一句
    这句**完全正确**：数据里关于屏幕就只有这一条 cons，模型没有编、
    没有超出证据。但用户问"怎么样"，得到的是一句像标题的话，
    他会觉得系统在敷衍（或者以为我没别的可说）。

    数据只有一条也必须讲成人话：这条意味着什么、要不要紧、
    什么情况下会碍事 —— 这些都是**解释**，不是新事实，不需要编数据。

    判据：用户问的是开放式问题（OPEN_ENDED），回答 < 25 字或只有一句。

    ⚠️ 封闭式问题不走这条。「多重？」「保修几年？」一句话答完是对的，
    硬撑成三段反而是废话。
    """
    t = (text or "").strip()
    if not t:
        return False
    q = user_text or ""
    if not any(w in q for w in OPEN_ENDED):
        return False
    # 只数中文句号/问号/感叹号切出来的句子，逗号不算
    sentences = [s for s in re.split(r"[。！？!?]", t) if s.strip()]
    return len(t) < 25 or len(sentences) <= 1


