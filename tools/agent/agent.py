NEGATE_CURRENT = ["不行", "不合适", "不适合", "不要了", "换掉", "算了"]

# 上面这组词原来是 `any(k in text ...)` 判的。中文里**疑问句把否定词包在中间**，
# 字面包含就判否，会把「问」当成「否」—— 实测 2026-11-11（第七轮）：
#   「这台行不行」     → 命中「不行」→ 判成用户否掉这台 → 推一台新的   ✘
#   「这台不合适吗」   → 命中「不合适」→ 同上                          ✘
#   「这个性能行不行」 → 同上                                          ✘
# 用户只是在问「行不行」，突然被塞了台别的机器 —— 这是最容易被骂"听不懂人话"的一类。
#
# 判据分两步：先认出疑问句式，剩下的才算真否定。
#   ① A不A 正反问：「行不行」「合适不合适」「够不够」「好不好」
#   ② 句末疑问语气：「…吗 / 嘛 / 么 / 呢」，或整句以问号收尾
_NOTA_Q = re.compile(r"([\u4e00-\u9fa5]{1,3})\s*不\s*\1")
_Q_TAIL = re.compile(r"[吗嘛么呢]\s*[？?]?\s*$|[？?]\s*$")


def _negates_current(text):
    """这句是不是在**否掉**当前这台（不是问它行不行）。

    歧义如实说明：「这台不合适吗」两种读法都通（真问 / 反问式否定）。
    这里选**当疑问**处理 —— 判错方向时，用户还能补一句「就是不行」；
    反过来判成否定就直接换台，用户会觉得系统自己瞎猜。
    """
    if not any(k in text for k in NEGATE_CURRENT):
        return False
    if _NOTA_Q.search(text):
        return False
    if _Q_TAIL.search(text):
        return False
    return True

