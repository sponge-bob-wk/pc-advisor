def _is_screen_fact(s):
    """一条事实是不是在讲**屏幕本身**（不是黑屏之类的故障）。"""
    if any(b in s for b in SCR_BAD_KW):
        return False
    return any(k in s for k in SCR_KW)


def _topic_of(user_text):
    """这句话问的是哪一项；问不出具体项（"怎么样/值不值"）就返回 None。"""
    q = user_text or ""
    for name, trig in TOPIC_TRIGGER.items():
        if any(t in q for t in trig):
            return name
    return None


def _topic_facts(m, user_text):
    """按提问主题裁一次事实：返回 (主题名, 优点子集, 缺点子集)。

    ⚠️ 裁不到就**原样返回**，不能把数据裁空 ——
    裁空会让模型只能答"库里没有"，那是另一种错误（见宪法第 2 条）。
    """
    topic = _topic_of(user_text)
    if not topic:
        return None, list(m.get("pros") or []), list(m.get("cons") or [])
    pros = list(m.get("pros") or [])
    cons = list(m.get("cons") or [])
    if topic == "屏幕":
        tp = [x for x in pros if _is_screen_fact(x)]
        tc = [x for x in cons if _is_screen_fact(x)]
    else:
        kws = TOPIC_FACT_KW.get(topic) or []
        tp = [x for x in pros if any(k in x for k in kws)]
        tc = [x for x in cons if any(k in x for k in kws)]
    if not tp and not tc:
        return topic, pros, cons
    return topic, tp, tc


