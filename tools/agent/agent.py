def _other_model_pitch(text, result):
    """把「另一台更值得买」说成了推荐理由 —— 偷偷换了推荐对象。

    实测 2026-11-11（演示前实跑）：
      数据 caution 原文：「小新 16SE 有双 M.2 硬盘位，同价位更值得看」
      模型输出：「要提醒的坑是：小新 16SE 有双 M.2 硬盘位，同价位更值得看」
    这句话每个字都有出处（所以 verify_answer 放行），但它把"另一台更好"
    包装成了"这台的坑"，等于在首位推荐的段落里主推了另一个型号。

    判据：出现「更值得 / 更好 / 推荐 / 不如买」这类比较词，
    且同一个分句里出现了**当前首位机型名字之外**的型号线索。
    不能只按词判 —— 数据原话本身就含这些字，要能区分"复述"和"主推"。
    """
    ranked = (result or {}).get("ranked") or []
    if not ranked:
        return False
    cur = ranked[0].get("name") or ""
    # 拆分句，避免跨句误判
    for seg in re.split(r"[。；！？\n]", text or ""):
        if not seg.strip():
            continue
        if not re.search(r"更值得|更划算|更推荐|不如买|推荐买|更合适|更好|更强", seg):
            continue
        # 这一分句里有没有"当前机型"？有就说明在说它自己，放行。
        # 🔴 2026-11-12：原来只写 `if cur in seg`，会被**型号前缀**骗过 ——
        #   cur=「联想小新 16」，seg=「联想小新 16SE 更值得看」，
        #   子串命中就放行，等于"16SE"冒充"16"。
        #   （现有测试用的是「小新 16SE」不带联想，恰好躲过这个洞。）
        #   改判：命中处后面紧跟 SE/Pro/Plus/数字/字母 → 那是另一个型号，不算它自己。
        _self = False
        if cur and cur in seg:
            for _mm in re.finditer(re.escape(cur), seg):
                _tail = seg[_mm.end():_mm.end() + 4]
                if re.match(r"\s?(?:SE|Pro|Plus|Max|Air|锐龙|酷睿|Ultra|\d|[A-Za-z])",
                            _tail):
                    continue      # 只是前缀，说的是 16SE 这种另一台
                _self = True
                break
        if _self:
            continue
        # 🔴 虚指变体（2026-11-12 实测）：
        #   「且这个价位同价位更值得看的机型**可能不在当前推荐里**」
        # —— 没点名任何型号，所以上面那条"型号线索"判据放行了。
        # 但它比点名更糟：用户不知道说的是哪台，只知道"我可能被坑了还没被告知"。
        # 这种悬空比较必须拦 —— 要么说清楚是哪台，要么别说。
        if re.search(r"更值得看.{0,12}(机型|的|可能)|"
                     r"不在(当前|这次)?推荐|没在推荐里|还有个更好|"
                     r"(更好|更强|更划算)的(机型|机器|选择)", seg):
            return True
        # 有没有别的型号线索（英文+数字组合，或"XX SE / Pro / Plus / 系列"）
        if re.search(r"[A-Za-z]{1,6}\s?\d{2,4}(?:SE|Pro|Plus|Max|Air)?", seg) \
                or re.search(r"(?:SE|Pro|Plus|Max)\b", seg) \
                or re.search(r"另一台|别的型号|另一款", seg):
            return True
    return False


def _tangent(text, user_text):
    """回答扯了用户没问的话题。只抓明显的：说了"库里没有X"但X不是用户问的。"""
    for topic, kws in UNASKED_TOPICS.items():
        asked = any(k in user_text for k in kws)
        if asked:
            continue
        # 出现"库里没有…故障率" 这类，且用户没问
        if ("库里没有" in text or "库里没" in text) and topic in text:
            return True
        if "库里没有" in text and any(k in text for k in kws):
            return True
    return False


def _warranty_stretch(text, corpus):
    """「保修一年」「保修期一年」在数据里找不到原话 → 语义扩大。
    数据里只有「一年上门保修」这种说法，那是服务，不是整机保修期。"""
    import re as _re
    hits = _re.findall(r"保修\s*(期)?\s*(一年|1\s*年|两年|两年|三年|两年)", text)
    if not hits:
        return False
    # 数据原话里如果有"保修一年"就不算扩大
    if "保修一年" in corpus or "保修期一年" in corpus:
        return False
    return True


def _foreign_fact(text, m):
    """回答里的信息属于**别的机型**，不属于当前这台。

    🔴🔴 为什么必须有（2026-11-11 演示彩排，本产品最严重的一次事故）：
      问：联想小新 16「这机器保修几年」
      答：「库里没有这项数据。这台机器提供「一年上门保修」服务。」

    这句话看起来完美：不编造、不跑题、还给了落点。但它说的
    **「一年上门保修」根本不是小新 16 的数据** ——
    全库只有一处写着这句，是 `offers[6]` **惠普战 66** 的 pros[2]。

    也就是说模型把 A 机器的售后信息，安到了 B 机器头上。
    这比编造更危险：
      · 编造容易被"数据里没有这个词"抓住
      · 串台用的是**真实存在的数据**，所有现成判据全部放行
      · 用户查证时能在库里找到这句，反而更信任 —— 但它是错的

    ⚠️ 判据必须**双向核对**，不能只看"数据里有没有"：
      · 只查"库里有这句" → 通过（战 66 有）→ 漏
      · 要查"这句是不是这台的" → 才能抓到

    实现：找出这句 / 这个短语是否是**别的机型独有**的。
    方法：把回答切成 6 字以上的片段，逐段检查 —— 若某段在这台的语料里
    找不到，却能匹配到**另一台**的语料，就是串台。

    只对追问路径用（数据面窄、可比对），并且要求片段足够长，
    避免"屏幕""内存"这类通用词互相碰撞。
    """
    t = (text or "").strip()
    if not t or not m:
        return None
    my_id = m.get("id")
    mine = _one_corpus(m)
    if not mine:
        return None

    # 收集别的机型的语料（只取有评价的那层，22 台，成本很低）
    try:
        others = []
        for o in core.load().get("offers") or []:
            if o.get("id") == my_id or o.get("cat") not in core.ALLOWED_CATS:
                continue
            c = _one_corpus(o)
            if c:
                others.append((o.get("name") or "", c))
    except Exception:
        return None
    if not others:
        return None

    # 从回答里切出"可能是事实陈述"的片段。
    # 🔴 固定长度 n-gram 这条路走不通，两个方向都试过：
    #   · N=6 → 误判 95%（撞上「屏幕素质在同」这类跨机型套话）
    #   · N=8 → 漏掉真正的事故（「一年上门保修」只有 6 字，短语生成不出来）
    #   根源：**事实的长度不确定**。"一年上门保修" 6 字，
    #   "一年上门保修，不用自己跑网点" 13 字，都是一件事。
    #
    # ⇒ 不用固定窗口，改成按**语义单元**取：先把别家语料按标点切成短句，
    #    再取每个短句里的「关键短语」（数字/专有词开头的那一小段）。
    #    这样长度跟着内容走，不跟窗口走。
    #
    # 判据三段：
    #   ① 这段在回答里出现
    #   ② 这台自己的语料里没有（不是它说的）
    #   ③ 全库只有**这一台**有（不是通用说法）
    ans = re.sub(r"\s+", "", t)
    all_corpora = [mine] + [c for _, c in others]

    # 「具体事实」的标志：数字，或这些专有名词
    CONCRETE = re.compile(
        r"\d|保修|上门|军标|认证|插槽|固态|独显|核显|色域|sRGB|刷新率|"
        r"分辨率|触控|雾面|镜面|泼溅|网点|模具|热管|雷电|"
        r"内存|硬盘|电池|续航|重量|Hz")

    for oname, ocurpus in others:
        # 按标点切短句，每句内再找"具体事实"片段
        for seg in re.split(r"[，。；、！？!?：:\n]", ocurpus):
            if len(seg) < 4:
                continue
            # ① 先尝试取"含具体标志"的最短片段（"一年上门保修"这种）
            cands = []
            for start in range(len(seg)):
                for end in range(start + 5, min(start + 16, len(seg)) + 1):
                    c = seg[start:end]
                    if CONCRETE.search(c):
                        while end - 1 > start + 4 and CONCRETE.search(seg[start:end - 1]):
                            end -= 1
                        cands.append(seg[start:end])
                        break
            # ② 兜底：整句本身就是短事实（"机身塑料感明显" 7 字、"接口给得比较全" 7 字）
            #    这类不含数字也不含专有词，但整句就是一件事。
            #    不加这条召回只有 46%（2772 次压测漏了 1491 次），
            #    漏的全是这种"描述型事实"。
            if len(seg) <= 18:
                cands.append(seg)

            for g in cands:
                if len(g) < 4:
                    continue
                if g in mine:                    # 这台也说了 → 不是串台
                    continue
                # 「多台共用」有两种情况，必须分开：
                #   ① 行业套话（"屏幕素质在同价位"）→ 不是谁的独有事实，说了不算串台
                #   ② 多台各自都有的事实（"内存板载"、"满载风扇噪音偏大"）
                #      → 仍然算串台！因为对**这台**来说它可能是假的。
                # 实测 2026-11-11：第一版一律排除共用短语，漏了 63 条 ——
                # 全是「满载风扇噪音偏大」和「内存板载」这两句，
                # 它们是 3 台各自的真实缺点，但对其它 19 台都是错的。
                # ⇒ 只有"含具体标志的短语"才享受"共用即通用"的豁免；
                #   "描述型短句"即使共用也照抓。
                if CONCRETE.search(g) and sum(1 for c in all_corpora if g in c) > 1:
                    continue
                if g in ans:
                    return {"frag": g, "from": oname}
    return None


def _one_corpus(o):
    """一台机器的可引用语料。

    🔴 字段之间必须留分隔符，不能直接拼。
    实测 2026-11-11：原来用空格 join 再去空白，字段边界就没了 ——
      战 66 的 pros 是「军标认证，键盘防泼溅」+「一年上门保修，不用自己跑网点」
      → 去空白后粘成「键盘防泼溅一年上门保修」
      → 从这个粘出来的假句子里取短语，取到的是跨字段的假片段，
        真正的「一年上门保修」反而没被识别成独立片段。
    改成用「。」连接：既保留字段边界（切句时能切开），
    又不引入英文标点导致后续正则失配。
    """
    if not o:
        return ""
    parts = [o.get("tag") or "", o.get("caution") or "", o.get("spec") or ""]
    parts += list(o.get("pros") or []) + list(o.get("cons") or [])
    s = "。".join(x for x in parts if x)
    return re.sub(r"\s+", "", s)


def _screen_part(spec):
    """从 spec 里**只切出屏幕那一段**，不要整条念。

    🔴🔴 为什么必须有（2026-11-12 实测）：
      天选 7 的 spec 是
        「R7 H260 · 16G + 512G · RTX 5050 · 2.5K 165Hz OLED」
      用户问「屏幕怎么样」，回答把**整条 spec** 念了出来 ——
      问屏幕，得到的是 CPU 和内存。原因是最外层判据写成
        `if any(k in spec for k in SCR_KW)`   # SCR_KW 含「OLED」
      只要 spec 里带 OLED 就整条命中，于是整句被当屏幕参数。
      判据必须落在**片段**上，不能落在整条上。

    做法：按 「·」 切段，逐段判是不是屏幕属性，只留中的段。
    ⚠️ 光按「·」切还不够：采集池生成的 spec 里屏幕跟显卡之间是用**空格**接的
      （「R9-9955HX · 16G + 1T · RTX 5070 16 寸 2560×1600 IPS 300Hz 100% sRGB」），
      整段会连着显卡一起被留下 —— 用户问屏幕，答里冒出「RTX 5070」。
      所以每段还要再按「屏幕从哪儿开始」切一刀，把前面的非屏幕部分剥掉。
    """
    s = (spec or "").strip()
    if not s:
        return ""
    # 屏幕相关的**部件属性**词。注意不能收「屏」这个单字 ——
    # 「黑屏」里也有屏字，那是故障现象不是屏幕规格（2026-11-11 踩过）。
    SCR = ["寸", "英寸", "×", "x2", "OLED", "IPS", "LCD", "VA", "MiniLED",
           "Hz", "刷新率", "分辨率", "2.5K", "2.8K", "2K", "3K", "4K", "1080",
           "16:9", "16:10", "sRGB", "DCI-P3", "AdobeRGB", "色域", "亮度",
           "nit", "雾面", "镜面", "触控", "防眩光"]
    BAD = ["黑屏", "花屏", "闪屏", "蓝屏", "死机", "虚焊", "通病"]
    # 「屏幕从哪儿开始」的锚点，取最早命中的那个位置
    ANCHOR = re.compile(
        r"\d+(?:\.\d+)?\s*(?:寸|英寸)"
        r"|\d{3,4}\s*[×xX]\s*\d{3,4}"
        r"|\b(?:2\.5K|2\.8K|2K|3K|4K|1080P|1440P|FHD|QHD)\b",
        re.I)
    keep = []
    for seg in re.split(r"\s*[·/|]\s*", s):
        seg = seg.strip()
        if not seg or any(b in seg for b in BAD):
            continue
        # 反例：「1TB」里含 T、但含 1T 不该算屏幕；这里靠 SCR 里没有裸 T 保证。
        if not any(k in seg for k in SCR):
            continue
        a = ANCHOR.search(seg)
        if a and a.start() > 0:
            seg = seg[a.start():].strip()
        keep.append(seg)
    return " · ".join(keep)


