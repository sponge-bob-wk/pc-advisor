# ---- 「最 X」排序断言：库里能核的放，核不了的拦 ---------------------------
# 实测 2026-11-11（第六轮对抗）：「这个价在市场上算什么水平」→
#   「这台联想小新 Air14 在轻薄本里算**最贵的一台**，但比库内最贵的 6799 元便宜不少」
# 两处都错：① 5100 在 10 台里排第 3，不是最贵；② 同一句里说"最贵"又说"比最贵的便宜"。
# _overspec() 完全没覆盖这类（它只管"这个价位能拿到 2.5K 屏"这类配置断言）。
#
# 难点：「最」本身不一定是错 —— 「全库最便宜的就是它」是**可核实且正确**的。
# 只用文案判会把合法陈述一起拦掉（实测误抓 3 条），那是判据没分辨力。
# 所以分两层：
#   可核实维度（贵/便宜/轻/重、价格最高最低）→ 交给数据层核对，这里不拦
#   不可核实维度（好/强/值/划算/耐用/省电/屏幕素质/噪音）→ 库里根本没这字段，一律拦
SUPER_SEG = re.compile(
    r"最[^，。；！？\n]{0,10}"
    r"|排名第[一二三四五零]|数一数二|首屈一指|位居第一|排在第一|销量第一|全库第一")

SUPER_UNCHECKABLE = ("好", "强", "快", "值", "划算", "耐用", "省电", "安静",
                     "厚", "薄", "优", "手感", "高", "低")
SUPER_CHECKABLE = ("贵", "便宜", "轻", "重")

# 说「价格本身最高/最低」是可核实的（库里有 price 字段）。各种说法要列全。
PRICE_LOWHIGH = re.compile(
    r"(最高价|最低价|价格最高|价格最低|价位最高|价位最低"
    r"|到手价最高|到手价最低|售价最高|售价最低|全库最高|全库最低|价最低|价最高)")

# 带免责的说法等于把范围限定住了，不算过度断言
SUPER_HEDGE = re.compile(r"(之一|按库内|按本库|库内|在本库|以库里|库里只有)")


def super_claims(text):
    """找出「最 X」里**库里无法核实**的那些排序断言。

    可核实的（价格最贵/最便宜/最轻/最重、价格最高最低）不在这里拦 ——
    它们的对错要用数据判，交给 verify_answer / audit_data 那一层。
    """
    out = []
    for m in SUPER_SEG.finditer(text):
        seg = m.group(0)
        ctx = text[max(0, m.start() - 8):m.end() + 10]
        if SUPER_HEDGE.search(ctx):
            continue
        if PRICE_LOWHIGH.search(seg) or PRICE_LOWHIGH.search(ctx):
            continue
        hit = None
        # 按词长优先：先看长的词，避免「便宜」被「薄」抢走
        for w in sorted(SUPER_UNCHECKABLE + SUPER_CHECKABLE, key=len, reverse=True):
            if w in seg:
                hit = w
                break
        if hit is None:
            if re.search(r"排名第[一二三四五零]|数一数二|首屈一指|位居第一|排在第一|销量第一", seg):
                out.append(seg.strip())
            continue
        if hit in SUPER_UNCHECKABLE:
            out.append(seg.strip())
    return out

