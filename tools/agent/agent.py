def _answer_price_position(user_text, o, focus):
    """回答「这台的价在库里算什么水平」。

    🔴 核心：**价格位置由代码算，模型只负责措辞。**
    实测 2026-11-11：这句原来掉进 recommend 分支，模型看到"这是榜首"，
    就编出「在轻薄本里算最贵的一台」——实际 5100 在 10 台里排第 3。
    价格排名是纯计算，没有任何理由让模型猜。
    """
    cat = o.get("cat")
    peers = [x for x in core.load()["offers"]
             if x.get("cat") == cat and x.get("price") and x.get("id") != o.get("id")]
    price = o.get("price")
    cat_name = core.CAT_NAMES.get(cat, cat)

    if not price:
        return {"stage": "compare", "slots": {}, "reply":
                "这台库里没记价格，我算不了它在什么位置。", "focus": focus,
                "focusName": o.get("name"), "questions": [], "warnings": [],
                "dataAsOf": core.data_as_of(), "outside_products": [],
                "untraceable_numbers": [], "fabricated_words": []}

    allp = sorted([price] + [x["price"] for x in peers], reverse=True)
    rank = allp.index(price) + 1
    n = len(allp)
    cheaper = [x for x in peers if x["price"] < price]
    pricier = [x for x in peers if x["price"] > price]
    sub = core.subsidy_of(price)

    # 位置描述只用算出来的事实，不写"最X"除非真的是
    if rank == 1 and n > 1:
        pos = "在库里 %d 台%s里是最贵的" % (n, cat_name)
    elif rank == n and n > 1:
        pos = "在库里 %d 台%s里是最便宜的" % (n, cat_name)
    else:
        pos = "在库里 %d 台%s里排第 %d 贵（比它贵的有 %d 台，比它便宜的有 %d 台）" % (
            n, cat_name, rank, len(pricier), len(cheaper))

    lines = [
        "%s 到手 ¥%s，%s。" % (o["name"], price, pos),
        "价格我没有「市场均价」这个概念 —— 库里只有这 %d 台自己的到手价，"
        "所以「划算不划算」我只能按这个范围说，不代表市面。" % n,
    ]
    if pricier:
        cheapest_up = min(pricier, key=lambda x: x["price"])
        lines.append("比它贵的那台是 %s，¥%s，贵 ¥%d。"
                     % (cheapest_up["name"], cheapest_up["price"],
                        cheapest_up["price"] - price))
    if cheaper:
        near = max(cheaper, key=lambda x: x["price"])
        lines.append("比它便宜又最接近的是 %s，¥%s，便宜 ¥%d。"
                     % (near["name"], near["price"], price - near["price"]))
    if sub:
        lines.append("原价 ¥%s，其中含国补 ¥%s。" % (sub["original"], sub["subsidy"]))

    reply = "\n".join(lines)
    return {"stage": "compare", "slots": {}, "reply": reply,
            "focus": focus, "focusName": o.get("name"),
            "questions": [], "warnings": [], "dataAsOf": core.data_as_of(),
            "outside_products": [], "untraceable_numbers": [],
            "fabricated_words": [], "priceRank": {"rank": rank, "of": n}}


