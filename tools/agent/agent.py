def parse_constraints(text, slots):
    """从用户话里提取硬性排除条件，放进 slots 跨轮保留。
    实测教训：用户说「不要封装内存」，系统还在推 upgrade=0 的机型，
    因为 upgrade 只是软权重、不是过滤条件。这类明确要求必须变成硬约束。"""
    t = text
    if any(k in t for k in ["不要封装", "别封装", "不要板载", "别板载", "不要焊",
                            "不能焊", "不要焊死", "不想要封装", "不要这种内存"]):
        # 双重否定：「不是不要封装」= 要封装，不能当硬约束
        if not re.search(r"不是\s*不要封装|并非\s*不要封装|不是\s*不想要封装", t):
            slots["_minUpgrade"] = 1
    if any(k in t for k in ["要能加内存", "能升级内存", "要能升级", "内存插槽",
                            "要可加装", "以后加内存", "留插槽"]):
        slots["_minUpgrade"] = 1
    if any(k in t for k in ["封装也行", "板载也行", "不用升级", "不能升级也没关系"]):
        slots.pop("_minUpgrade", None)

    # 内存容量下限：「32G 内存」「要 32G」→ _minRam=32
    m = re.search(r"(\d{1,3})\s*[Gg]\s*(内存|运存)?", t)
    if m and any(w in t for w in ["内存", "运存", "G"]):
        v = int(m.group(1))
        if v in (16, 24, 32, 48, 64):
            slots["_minRam"] = v
    # 「不要荣耀」「除了荣耀其他都行」→ 品牌排除。
    # 必须先确认后面那两个字真的是库里的品牌，否则「不要封装」会被当成排除品牌"封装"。
    m = re.search(r"(不要|别买|除了|不想要)\s*([\u4e00-\u9fa5]{2,4}?)(?=其他|都行|的|，|,|；|。|$)", t)
    if m:
        cand = m.group(2)
        real = {o.get("brand") for o in core.usable_offers(core.load())}
        if cand in real:
            slots.setdefault("_excludeBrand", [])
            if cand not in slots["_excludeBrand"]:
                slots["_excludeBrand"].append(cand)
    return slots


def template_reply(m):
    """换一台用模板拼，不调模型。
    实测：多轮「换一台」时模型会把当前这台说成「你不想要的」，
    还会冒出库外品牌。这类回答数据是现成的，稳定比文采重要。
    缺点优先挑「封装/板载」这类决定性信息 —— 之前只挑第一条，
    结果漏掉了「内存板载」，用户看到前后矛盾。"""
    parts = ["%s，%s，到手 ¥%s。" % (m["name"], m.get("spec") or "", m.get("price"))]
    pros = [p for p in (m.get("pros") or []) if p]
    if pros:
        parts.append(pros[0].rstrip("。") + "。")
    cons = [c for c in (m.get("cons") or []) if c]
    key = next((c for c in cons if any(w in c for w in ["封装", "板载", "焊"])), None)
    if key is None and cons:
        key = cons[0]
    if key:
        parts.append("有件事得先说清楚：" + key.rstrip("。") + "。")
    elif m.get("caution"):
        parts.append("不过要注意：" + m["caution"].rstrip("。") + "。")
    # 采集池那批没有 pros/cons —— 必须自己说出来，否则用户以为上面那句就是全部评价。
    # 实测 2026-11-12：兜底模板对无评价机型只输出「名字+配置+价格」，
    # 用户读到的是一条干巴巴的参数，却不知道"没有评价"和"评价不错"是两件事。
    if not pros and not cons:
        parts.append("这台的评价库里还没有 —— 上面这些是配置和价格，"
                     "好不好用得你看实机或第三方评测。")
    return "".join(parts)


def _money(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "—"
    return ("%d" % v) if v.is_integer() else ("%.2f" % v)


def _list_others_reply(rest, slots):
    """把第 2 名之后的候选逐台写出来。**全部由代码生成**，不经过模型。

    为什么不让模型写：它每次都会把首位那台再介绍一遍（实测三次），
    因为它看到的"数据"里首位最完整，而"列其余"这个动作没有任何字段约束它。
    清单这种确定性输出，交给模板比交给模型稳。

    只说数据里有的：机型 / 配置 / 到手价 / 有没有人写过优缺点。
    ⚠️ 没人评过的机器**不许加一句评价**（宪法第 7 条）。
    """
    if not rest:
        return ""
    lines = ["除了刚才那台，同样条件下库里还有 %d 台（按同一套规则排出来的第 2 名往后，"
             "不是我另外换了一台）：" % len(rest)]
    for i, m in enumerate(rest, 2):
        seg = "%d. %s —— %s，到手 ¥%s。" % (
            i, m["name"], m.get("spec") or "配置未记", _money(m.get("price")))
        if m.get("hasReview"):
            seg += "这台库里有人写过优缺点，要展开可以点它问。"
        else:
            seg += "这台库里没人写过优缺点，只有配置和价格。"
        if m.get("noPerfData"):
            seg += "另外它查不到跑分，排序是按价格排进来的。"
        lines.append(seg)
    lines.append("想看哪台的具体参数或短板，直接点名就行。")
    return "\n".join(lines)


def _compare_text(rows):
    """把 2–3 台摆在一起。**只报字段，不做推荐、不给评分。**

    为什么不交给模型：对比要求每个数字都对上号，
    4B 模型很容易把 A 的价格配到 B 的名字上（串台），模板反而更稳。
    结论行只做**可核对的数据比较**（谁最便宜、谁的跑分最高），
    不说"更值得买"。
    """
    if len(rows) < 2:
        return "库里这个条件下只有一台，没有可对比的第二台。"
    L = ["放一起看（每个数都是库里的字段，不是我算的印象）："]
    for r in rows:
        bits = ["到手 ¥%s" % _money(r.get("price"))]
        bits.append("%sG 内存" % r["ram"] if r.get("ram") else "内存未记")
        bits.append("跑分 %s" % r["perf"] if r.get("perf") is not None else "跑分库里没有")
        bits.append("重量 %s" % (("%s kg" % r["weightKg"]) if r.get("weightKg")
                                else "库里没记"))
        u = r.get("upgrade")
        bits.append("内存焊死" if not u else "可加装 %s/3 档" % u)
        if r.get("hasReview") is False:
            bits.append("没人写过优缺点")
        L.append("· **%s** —— %s" % (r["name"], "，".join(bits)))

    # 结论：只用上面已列出的字段做比较，不引入任何新判断
    cheap = min(rows, key=lambda x: x.get("price") or 9e18)
    L.append("")
    L.append("光看数字：最便宜的是 %s（¥%s）。" % (cheap["name"], _money(cheap.get("price"))))
    perf_rows = [r for r in rows if r.get("perf") is not None]
    if len(perf_rows) >= 2:
        top = max(perf_rows, key=lambda x: x["perf"])
        if all(r["perf"] == top["perf"] for r in perf_rows):
            L.append("这三台的跑分都是 %s，性能这一项没有差别。" % top["perf"])
        else:
            L.append("跑分最高的是 %s（%s）。" % (top["name"], top["perf"]))
    wt = [r for r in rows if r.get("weightKg")]
    if len(wt) >= 2:
        light = min(wt, key=lambda x: x["weightKg"])
        L.append("有重量记录的两台里，%s 最轻（%s kg）。" % (light["name"], light["weightKg"]))
    elif len(wt) == 1:
        L.append("只有 %s 记了重量（%s kg），其余库里没记 —— 不拿没记的当轻。"
                 % (wt[0]["name"], wt[0]["weightKg"]))
    return "\n".join(L)


