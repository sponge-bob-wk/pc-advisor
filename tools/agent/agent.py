# 结论词表。判据要能分辨：说岔了要被抓到，说对了不能误判。
_VERDICT_TOKENS = {"match": ["匹配", "合适", "适合", "够用", "没问题"],
                   "partial": ["部分匹配", "勉强", "一般", "够呛", "打折"],
                   "mismatch": ["不匹配", "不适合", "不合适", "不太行", "不是游戏本",
                                "别拿它", "不建议", "扛不住", "跑不动"]}


def _verdict_wrong(text, verdict):
    """检查模型说出口的结论和系统判定是否一致。
    分辨力说明：mismatch 时只要出现「部分匹配/勉强/一般」这类弱化词就算错；
    但「不合适」本身含「合适」，所以先长词优先匹配，避免把自己判错。"""
    if verdict is None:
        return False
    long_first = sorted(_VERDICT_TOKENS[verdict], key=len, reverse=True)
    said_ok = any(t in text for t in long_first)
    if verdict == "mismatch":
        # 说了"不合适"之后又冒出"部分匹配/勉强"的，是自相矛盾
        soft = [t for t in _VERDICT_TOKENS["partial"] if t in text]
        return bool(soft) or not said_ok
    if verdict == "match":
        return not said_ok
    return False


def _corpus_of(offers):
    parts = []
    for o in offers:
        parts += [o.get("spec") or "", o.get("tag") or "", o.get("caution") or "",
                  o.get("name") or ""]
        parts += o.get("pros") or []
        parts += o.get("cons") or []
    return " ".join(parts)


