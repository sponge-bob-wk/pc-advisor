def _clean_brand_note(note, m):
    """品牌级备注里如果夹带了**具体机型**的内容，不能当本机信息说。

    实测 2026-11-11（演示前实跑）：联想品牌的 note 原文是
      「同一个品牌里，E14 能加内存、X1C 不能 —— 别按品牌判断，按型号判断。
        小新 16SE 的双 M.2 硬盘位是今年的卖点。」
    后一句在说**另一台**（16SE），但它混在品牌备注里，
    用户问「这台保修几年」时，兜底模板把整段念了出来 ——
    等于在回答里安利了另一台，而且是库里未必有的型号。

    判据：品牌 note 按句拆开，含「型号线索」但又**不是这台**的句子丢掉。
    型号线索 = 英文+数字（E14/X1C/16SE）或「XX Pro/SE/Plus」。
    """
    note = (note or "").strip()
    if not note:
        return ""
    name = m.get("name") or ""
    keep = []
    for seg in re.split(r"[。；]", note):
        seg = seg.strip()
        if not seg:
            continue
        # 这一句里的型号线索
        others = re.findall(r"[A-Za-z]{1,6}\s?\d{1,4}(?:SE|Pro|Plus|Max|Air)?"
                            r"|\d{2}\s?(?:SE|Pro|Plus)", seg)
        if not others:
            keep.append(seg)
            continue
        if name and name in seg:
            keep.append(seg)
            continue
        # 🔴 含别的型号 —— **默认丢弃**，只有明确是"方法论/品牌整体判断"才保留。
        #    （2026-11-12 修：原来这里是默认保留，只在命中几个词时才丢，
        #      结果华为的 note「MateBook D16 在 4589 元给到 1TB，是这一档里存储最宽的选择」
        #      被原样念进了「MateBook 14 2026 保修几年」的回答里 ——
        #      用户问 A 的售后，回答在讲 B 的存储。
        #      方向必须反过来：品牌备注里提别的型号，可疑的默认扔。）
        #
        # 保留的两种例外，都必须有明确的"非本机配置"特征：
        #   「E14 能加内存、X1C 不能 —— 别按品牌判断」→ 后半句是方法论
        #   「这个品牌整体性价比不错」→ 没提具体型号（上面 others 就不会命中）
        hints = re.findall(r"(别按\w+判断[^，。；]*|按型号判断|要按?\w*型号\w*)", seg)
        if hints:
            keep.extend(hints)
            continue
        if re.search(r"品牌整体|这个牌子整体|整个品牌|同代都", seg):
            keep.append(seg)
            continue
        # 其余一律丢弃 —— 它在讲某台的**具体配置/价格**，不是这台，也不是品牌概括
        continue
    return "，".join(k.strip("，。；——") for k in keep if k.strip("，。；——"))


def _followup_template(m, user_text):
    """追问的兜底：只回数据原文，不外推。

    这里的目标不是"答满"，而是**答得有用**：
    库里没有保修年限时，只回一句"库里没有这项数据"等于什么都没说。
    能说的是：这台有什么服务承诺（有就念）、品牌这块整体什么情况（有就说）、
    以及**你该怎么办**（去问谁、看哪）。这三样都不需要编数字。
    """
    corpus = (m.get("pros") or []) + (m.get("cons") or [])
    q = user_text
    # 问保修/售后 → 只讲库里有的服务描述
    if any(w in q for w in ["保修", "售后", "维修", "修"]):
        svc = [p for p in (m.get("pros") or []) if "保修" in p or "售后" in p]
        # 品牌 note 可能夹带别的机型，先过滤（见 _clean_brand_note）
        note = _clean_brand_note(m.get("brandNote"), m)
        parts = []
        if svc:
            parts.append("库里关于 %s 的售后只有这些：" % m["name"])
            parts.append("；".join(svc) + "。")
        if note:
            # note 是品牌层面的结论，单独成句前加个引子，否则像在说别的事
            parts.append("品牌这块还有一句：")
            parts.append(note.rstrip("。") + "。")
        if not svc and not note:
            parts.append("保修年限这一项，库里对 %s 没有记录。" % m["name"])
        # 不给年限也给个着落 —— 不然用户拿着一句"没有"就走了。
        # 这里不指定具体年数（那是编），只指路。
        parts.append("具体几年我不敢替厂商说 —— 这个数只有厂商的保修条款能定。"
                     "下单页的商品详情里有「保修」一栏，或者问客服要书面答复，"
                     "这两个地方的说法才作数。")
        return "".join(parts)
    if any(w in q for w in ["缺点", "短板", "问题", "不好"]):
        return ("%s 库里记的缺点是：%s。"
                % (m["name"], "；".join(c.rstrip("。") for c in (m.get("cons") or []))))
    # 问屏幕：只能讲数据里关于屏幕的那几条，不能把整份数据念一遍。
    # 实测 2026-11-11：兜底分支把 6 条优缺点全念了，用户问屏幕得到一段流水账。
    if any(w in q for w in ["屏幕", "色域", "色彩", "屏"]):
        # 词表在模块顶部（SCR_KW / SCR_BAD_KW / _is_screen_fact），
        # 模型那条路和这里共用同一份 —— 不再各写一遍。
        scr = [c for c in (m.get("cons") or []) if _is_screen_fact(c)]
        scr += [p for p in (m.get("pros") or []) if _is_screen_fact(p)]
        if scr:
            head = "库里关于 %s 屏幕就记了这些：" % m["name"]
            body = "；".join(x.rstrip("。") for x in scr) + "。"
            # 补一句它意味着什么 —— 这是解释，不是新事实，不需要编数据。
            tail = ""
            if any("不算突出" in x or "不突出" in x for x in scr):
                tail = ("说白了是同价位正常水平，写代码看文档没问题；"
                        "真要做调色，颜色不如标称高色域的机器准。")
            elif any("明显短板" in x or "低色域" in x or "窄" in x for x in scr):
                tail = ("这条对做设计/剪片是要紧的 —— 成片颜色会偏，"
                        "换台机器看可能和你调的色不一样。")
            return head + body + tail
        # 🔴 没有人工评价 ≠ 没有屏幕参数（2026-11-12 实测，很严重的一类错）
        #   问「MateBook 14 2026 屏幕怎么样」，原来答：
        #     「库里对这台屏幕没有单独记录 —— 是没查，不是查了没问题」
        #   可它的 spec 里明明写着「14.2 寸 2880×1920 OLED 120Hz 100% DCI-P3」。
        #   把**已有的数据说成没查**，和编造是同一条红线的两个方向：
        #   编造是"没有说有"，这个是"有说没有" —— 用户会因为这句放弃一台好机器。
        #   采集池那 78 台全部走这条缝：它们的 spec 带完整屏幕参数，但 pros/cons 为空。
        # ⚠️ 只能用 _screen_part() 切出屏幕那一段，**不能拿整条 spec 去判**
        #   （2026-11-12 二次实测：`any(k in spec for k in SCR_KW)` 里 SCR_KW 含
        #    「OLED」，天选 7 的 spec 带 OLED 就整条命中，于是问屏幕答出了
        #    「R7 H260 · 16G + 512G · RTX 5050」—— 问屏幕，答的是 CPU 和内存。）
        scr_spec = _screen_part(m.get("spec"))
        if scr_spec:
            return ("%s 的屏幕，参数是有的：%s。\n"
                    "库里没有人写过这块屏**用起来**怎么样（色准实测、观感这些没人评过），"
                    "所以优点缺点我不替它说 —— 参数在这儿，好不好你去店里看一眼最准。"
                    % (m["name"], scr_spec))
        # 数据里一个字都没提屏幕 → 明说没查，不能沉默（沉默会被读成"没问题"）
        return ("库里对 %s 的屏幕没有单独记录 —— 是**没查**，不是查了没问题。"
                "这个参数在商品详情页的「规格参数」里有，认「色域」那一行就行。"
                % m["name"])
    # 🔴 兜底：用户问的是别的某项（散热/键盘/续航…），库里没有按项分类的记录。
    #   2026-11-12 实测：原来这里把 pros+cons **6 条全念一遍** ——
    #     问「散热怎么样」，答里混进了「到手价最低的一台」「留给内存插槽」。
    #   数量问题是次要的，**串台**才是要害：用户会以为那些也是在讲散热。
    #   做法：能按关键词捞到相关的就只念相关的，捞不到就限定条数并声明。
    kw = []
    for w in ["散热", "发热", "温度", "风扇", "噪音", "键盘", "手感", "续航",
              "电池", "重量", "接口", "充电", "性能", "跑分", "内存", "硬盘",
              "存储", "扬声器", "音响", "摄像头"]:
        if w in q:
            kw.append(w)
    hit = [c for c in corpus if any(k in c for k in kw)] if kw else []
    if hit:
        return ("%s 库里跟这一项相关的只有这些：%s。"
                % (m["name"], "；".join(x.rstrip("。") for x in hit)))
    head = "%s，%s。" % (m["name"], m.get("spec") or "")
    if corpus:
        return (head + "库里没有按这一项单独记过评价，只有这些整体印象：%s。"
                % "；".join(x.rstrip("。") for x in corpus[:3]))
    return (head + "这台库里只有配置和价格，没有任何人写过评价 —— "
            "这一项好不好用得看实机或第三方评测。")

