def numbers_in(text):
    return set(int(x) for x in re.findall(r"\d{3,6}", text))


def allowed_numbers(result):
    """回答里允许出现的全部数字：来自内核，可追溯。"""
    ok = set()
    for r in result["ranked"]:
        for k in ("price", "perf", "upgrade", "portable"):
            v = r.get(k)
            # 🔴 必须收 float（2026-11-12 修）：
            # 接入采集池后价格带小数（¥6687.41 是国补后的实付价，不是拍脑袋的整数）。
            # 原来只写 isinstance(v, int)，浮点价被整个漏掉 ——
            # 模型如实报「到手 6687.41」，verify_answer 却判成"数据外数字"打回重写，
            # 重写又命中，最后落入兜底模板，一条本来正确的回答被自己人毙了。
            if isinstance(v, (int, float)):
                ok.add(int(round(v)))
                # 🔴 2026-11-12 乱测夹具抓到：价格 ¥4240.65 被误判成"数字不可追溯"。
                #   numbers_in() 只抽整数（"4240.65" → 4240），这里却按 round 记成 4241，
                #   小数价格必然对不上 → 一条如实报数的回答被自己人毙掉，白重写一次。
                #   两个都放行：截断值和四舍五入值都是这台机器真实价格的表示。
                ok.add(int(v))
        sub = r.get("subsidy") or {}
        for k in ("original", "subsidy", "paid"):
            if isinstance(sub.get(k), (int, float)):
                ok.add(int(round(sub[k])))
        # 规格里的型号数字（RTX 5060、2.5K 165Hz）属于真实数据，一并放行
        ok |= numbers_in(r.get("spec") or "")
        ok |= numbers_in(r.get("name") or "")
        # caution/tag 是库里人工写好的风险提示，本身就可能含数字
        # （例：暗影精灵 caution="比隐星贵 460，买的是品牌而不是性能"）
        ok |= numbers_in(r.get("caution") or "")
        ok |= numbers_in(r.get("tag") or "")
    for w in result["warnings"]:
        ok |= numbers_in(w)
    ok |= numbers_in(result["dataAsOf"])
    return ok


# 相对量断言：库里没有任何对比测量数据，凡是"多 X%""强 Y 倍""快一倍"全是模型编的。
# 实测 2026-11-11「8000 的台式机」：写出"比移动版多约 15% 的 CUDA 核心"，
# 而 numbers_in 只抓 3~6 位数字，15 是两位数，就这么漏过去了。
RELATIVE_CLAIM = re.compile(
    r"(多|高|快|强|低|少|省)\s*(出|了)?\s*(约|大约|将近|接近|差不多)?\s*"
    r"[\d一二三四五六七八九十]+\s*(%|％|倍)"
    r"|[\d一二三四五六七八九十]+\s*(%|％|倍)\s*(多|左右|以上)?"
    # 「双倍内存」「翻一番」「翻倍」这类口头倍数，不带"倍"字也算
    r"|(双倍|两倍|三倍|四倍|一倍|翻倍|翻一番|翻一翻)"
    r"|\d+\s*G\s*(内存|固态)?\s*翻"
    r"|(比|多)\s*(出|了)?\s*[\d一二三四五六七八九十]+\s*(G|T)(B)?")

# 语料里真实存在的倍数说法不误杀，但必须由语料判定，不能无条件豁免。
# 这里留空是有意的：_relative_claim 已经做了"整句在语料里才放行"的判断，
# 再加一层白名单就等于开后门 —— 实测 2026-11-11「内存翻倍」就是这么漏过去的。


def _corpus_all(result):
    """校验用的完整语料：本轮候选 + 数据源里的政策/趋势/跨品类说明。

    为什么要扩到顶层：实测 2026-11-11 答案里写"CUDA 核心比移动版多约 15%"，
    这句其实是 data.prices.json 的 crossSell 原文，不是模型编的。
    只拿本轮候选当语料会把真话判成编造，判据就成了误杀工具。
    """
    parts = [_data_corpus(result)]
    try:
        d = core.load()
        for k in ("subsidyRules", "subsidyFacts", "crossSell", "upgradeGuide",
                  "outlook", "budgetBands", "categoryChange", "sameModel",
                  "partsChange", "costShare", "trapsByKind", "defects"):
            if k in d:
                parts.append(json.dumps(d[k], ensure_ascii=False))
    except Exception:
        pass
    return " ".join(parts)


def _relative_claim(text, corpus):
    """相对量比较（多 15%、快一倍）。只有追不到数据出处的才算编造。

    实测两次教训：
    ① 第一版"一律拦"，把「国补按 15% 立减」「CUDA 核心比移动版多约 15%」
       这些数据原文也拦了 —— 判据没有分辨力。
    ② 改成"数字能在语料里找到就放行"，又漏光了：「强 3 倍」的 "3" 在语料里
       到处都是（"3 台""3.2K"），一撞就通过。
    正解：看「带数字的完整说法」在不在语料里，而不是只看数字。
    """
    out = []
    for m in RELATIVE_CLAIM.finditer(text):
        s = m.group(0).strip()
        # 去掉空格后整句比对，例如 "多约15%" 命中语料里的 "多约 15%"
        key = re.sub(r"\s+", "", s)
        flat = re.sub(r"\s+", "", corpus)
        if key and key in flat:
            continue
        out.append(s)
    return out


def verify_answer(text, result, user_text=""):
    """硬断言：回答里的数字必须能追到内核或用户原话。返回无法追溯的数字。"""
    allowed = allowed_numbers(result) | numbers_in(user_text)
    return sorted(numbers_in(text) - allowed)


OUTSIDE_BLACKLIST = ["XPS", "ThinkPad", "MacBook", "Mac ", "拯救者", "雷蛇",
                     "外星人", "Alienware", "Surface", "ROG", "幻16", "幻 16"]


def check_outside_products(text, data=None):
    """检查是否引入了库外产品线。否定语境（声明"库里没有"）不算违规。"""
    d = data or core.load()
    known_text = " ".join([o.get("name", "") for o in d["offers"]])
    NEG = ["没提", "不包含", "没有", "不在", "未收录", "别", "不要", "无法", "不涉及"]
    hits = []
    for w in OUTSIDE_BLACKLIST:
        if w not in text or w in known_text:
            continue
        # 只看出现该词的分句，若同句带否定词，说明是在声明范围外，不算违规
        bad = False
        for sent in re.split(r"[。！？；\n]", text):
            if w in sent and not any(n in sent for n in NEG):
                bad = True
                break
        if bad:
            hits.append(w.strip())
    return hits


OUT_OF_SCOPE = ["macbook", "mac ", "苹果电脑", "苹果笔记本", "苹果本", "ipad", "平板",
                "手机", "iphone", "安卓机", "ps5", "switch", "游戏机", "一体机"]
# ⚠️ 这份词表查的是**用户说了什么**（入口），`core.is_out_of_scope_offer` 查的是
#   **数据里那台机器是什么**（取数口子）。两者不是同一条判据抄两遍：
#   一个管"这话该不该接"，一个管"这台能不能进池子"。
#   但加词要成对看：2026-11-13 实测「苹果笔记本和这个比呢」漏在入口没拦住，
#   就是因为这里只有"苹果电脑"没有"苹果笔记本"。


def check_scope(text):
    """范围检查放在抽槽位之前。这类问题不该进澄清流程。"""
    t = text.lower()
    for w in OUT_OF_SCOPE:
        if w in t:
            return w.strip()
    return None


# 回答里**不该出现**的产品品类。库里只有 Windows 笔记本、台式整机、内存固态。
#
# 为什么要在出口查这个（2026-11-11 演示前实跑发现）：
#   「别指望它能完全替代专业设计工作站」—— 用户问的是轻薄本，
#   回答里把"专业设计工作站"当成对照物，这是库里根本没有的品类。
#   「小米笔记本的售后体系不如手机」—— 更直接，回答里冒出"手机"。
#   这些句子都不含数字，verify_answer 管不到；也不是新机型名，
#   check_outside_products 那个按数据比对的判据也管不到 —— 它只筛"库外机型名"。
OUT_SCOPE_PRODUCT = re.compile(
    r"手机|平板|iPad|iPhone|安卓机|"
    r"工作站|服务器|"
    r"MacBook|Mac\s*Book|苹果电脑|iMac|Mac\s*mini|"
    r"PS5|Switch|游戏机|主机党|"
    r"显卡坞|外接显卡")

# 这些是"顺带提一句"的正当用法，不算越界。
#   「比手机还便宜」—— 在说价格便宜，不是在介绍手机
#   「不是手机那种」—— 在划清界限
#   「比平板还轻」  —— 在说重量
# 注意「不如」**不在**豁免里：实测 2026-11-11，
#   「小米笔记本的售后体系不如手机」被豁免掉了 —— 但那是在拿手机做实质对照，
#   用户问的是笔记本售后，回答里出现了库里没有的品类当参照物，就是越界。
#   豁免只该给"用别的东西打比方说价格/重量/体积"，不该给"拿别的东西比性能/售后"。
OUT_SCOPE_EXCUSE = re.compile(
    r"(?:比|不像|不是|没有)\s*(?:手机|平板|工作站|MacBook|iPad|iMac)"
    r"[^，。；]{0,6}(?:还)?(?:便宜|贵|轻|重|薄|厚|小|大|省电)"
    r"|(?:手机|平板|工作站)\s*(?:那么|那种)")


def _out_scope_product(text):
    """回答里出现了库外品类 → 返回命中的词，供上层打回重写。"""
    for m in OUT_SCOPE_PRODUCT.finditer(text or ""):
        ctx = text[max(0, m.start() - 10):m.end() + 10]
        if OUT_SCOPE_EXCUSE.search(ctx):
            continue
        return m.group(0)
    return None


