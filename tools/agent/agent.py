BUDGET_LOWER = ["便宜点", "便宜些", "便宜一点", "再便宜", "降点价", "低一点"]

# 「都行」「随便」单独不能算数：用户说「除了荣耀其他都行」时也含"都行"，
# 但那是品牌排除，跟预算无关。实测 2026-11-11 就栽在这上面：
# 预算 5000 被丢掉、变成 _cheapest，推了 ¥3000 那台。
CN_NUM = {"零": 0, "一": 1, "两": 2, "二": 2, "三": 3, "四": 4, "五": 5,
          "六": 6, "七": 7, "八": 8, "九": 9}


UNIT = {"万": 10000, "千": 1000, "百": 100, "十": 10}
SMALL_UNIT = {"千": 1000, "百": 100, "十": 10}

# 「三四千」「五六千」「七八千」—— 两个数字连写表示区间。
# 实测 2026-11-11：_seg_val 把「三四」读成 34，于是「三四千」算出 34000，
# 「五六千」算出 56000，全错了一个量级。这是中文口语的固定格式，必须单独识别。
RANGE2 = re.compile(r"^([一二两三四五六七八九])([一二两三四五六七八九])([万千百])$")


def _range2_val(seg):
    """「三四千」→3500（区间中值）。不是金额语境时返回 None。"""
    m = RANGE2.match(seg)
    if not m:
        return None
    u = SMALL_UNIT[m.group(3)]
    lo, hi = CN_NUM[m.group(1)], CN_NUM[m.group(2)]
    if hi <= lo:          # 「九三」不是区间，交给原逻辑
        return None
    return (lo + hi) * u // 2


def _seg_val(seg):
    """算不带「万」的一段：「七千五」→7500、「二千五」→2500、「五百五」→550、
    「三四千」→3500。"""
    r = _range2_val(seg)
    if r:
        return r
    val = 0
    sec = 0
    last = None
    for ch in seg:
        if ch.isdigit():
            sec = sec * 10 + int(ch)
        elif ch in CN_NUM:
            sec = sec * 10 + CN_NUM[ch] if sec else CN_NUM[ch]
        elif ch in SMALL_UNIT:
            u = SMALL_UNIT[ch]
            val += (sec or 1) * u
            sec = 0
            last = u
    if sec:
        val += sec * (last // 10) if last else sec
    return val


def _cn_to_int(s):
    """中文口语金额 → 整数。支持「五千」「七千五」「五千八」「一万二」「一万二千五」「1.2万」「六千万」。

    2026-11-11 第二次重写：先按「万」切段、每段用 _seg_val 算完整段值，再进位。
    上一版按字符流一趟累加，在「六千万」上算出 16000（正确是 6×1000×10000），
    根因是"万"前的"六千"被当成了系数 6。
    """
    if not s:
        return None
    s = s.replace("块", "").replace("元", "").replace("钱", "").strip()
    # 「1.2万」「0.8万」
    m = re.fullmatch(r"(\d+(?:\.\d+)?)\s*万", s)
    if m:
        return int(round(float(m.group(1)) * 10000))
    if "万" in s:
        left, _, right = s.partition("万")
        total = _seg_val(left) * 10000
        if not right:
            return total
        # 「一万二」：万后孤立一位裸数字，按千补
        if re.fullmatch(r"[零一两二三四五六七八九\d]", right):
            total += (int(right) if right.isdigit() else CN_NUM[right]) * 1000
            return total
        total += _seg_val(right)
        return total or None
    return _seg_val(s) or None


def _budget_in_text(text):
    """用户原话里到底有没有金额。返回所有可能被理解为预算的数。"""
    # 千分位先并掉，否则「12,000」会被 \d{3,6} 拆成 12 和 000 两个"金额"，
    # 实测就是这个让 12000 的预算认不出来、反而判成 0。
    t = re.sub(r"(?<=\d),(?=\d{3})", "", text)
    # 「六千万像素」不是预算。实测 2026-11-11 这条被当成 6000 元预算，
    # 直接把"要拍照好"的需求换成了一次预算判断。先把非金额的「万」剔掉。
    t = re.sub(r"[零一两二三四五六七八九十百千\d.]+\s*万\s*(像素|毫安|mAh|赫兹|Hz|转)",
               "", t)
    t = re.sub(r"[零一两二三四五六七八九十百千\d.]+\s*(万)?\s*(像素|毫安时)", "", t)
    # 🔴 规格单位跟着的数字不是预算。实测 2026-11-12：「6000mAh 大电池」
    #   被抽成 budget=6000，用户一句电池需求变成了一次预算判断。
    #   电池容量/功耗类单位彻底剔掉（数字+单位连写是规格，不是钱）。
    t = re.sub(r"\d+(?:\.\d+)?\s*(?:mAh|毫安|瓦时|Wh)", "", t, flags=re.I)
    # 刷新率同理：「165Hz」是屏幕参数，不是 165 元的预算
    t = re.sub(r"\d+(?:\.\d+)?\s*(?:Hz|赫兹|转)", "", t, flags=re.I)
    nums = set(int(x) for x in re.findall(r"\d{3,6}", t))
    # 区间「5000 到 7000」——模型取上限或中值都算有出处
    m = re.search(r"(\d{3,6})\s*[到\-~]\s*(\d{3,6})", t)
    if m:
        lo, hi = int(m.group(1)), int(m.group(2))
        nums.update({lo, hi, (lo + hi) // 2})
    # 「1.2万」「0.8 万」这种小数万
    for m in re.finditer(r"(\d+(?:\.\d+)?)\s*万", t):
        v = int(float(m.group(1)) * 10000)
        if 500 <= v <= 200000:
            nums.add(v)
    # 中文金额：「七千」「一万二」「五千八」「七千五」「一万五」「一万二千五」
    # (?<![\d.]) 防止「1.2万」里的 "2万" 被再算一次 20000
    for m in re.finditer(
            r"(?<![\d.])[零一两二三四五六七八九\d]{1,3}[万千百][零一两二三四五六七八九千百\d]{0,3}", t):
        v = _cn_to_int(m.group(0))
        if v and 500 <= v <= 200000:
            nums.add(v)
    # 「六千上下浮动五百」「七千左右，能多五百」—— 基准 ± 浮动。
    # 实测 2026-11-11：模型给出 6500（=6000+500，完全正确），
    # 但语料里只有 6000 和 500，于是被判成编造、预算被清空。
    # 只要出现「上下/浮动/左右/多/少」这类词，就把 基准±浮动 都算成有出处。
    if re.search(r"(上下|浮动|左右|出头|以内|多|少|加|减)", t):
        base = [n for n in nums if n >= 1000]
        delta = [n for n in nums if n < 1000]
        for b in base:
            for d in delta:
                nums.add(b + d)
                if b - d >= 500:
                    nums.add(b - d)
    return nums


# 「不要七千的」「七千以上的别给我」——金额是被排除的对象，不是预算上限。
# 实测 2026-11-11：这句被读成 budget=7000，然后推了一台 6799 的，
# 正好落在"七千"这条线上，用户明确说过不要。
BUDGET_NEG = re.compile(
    r"(不要|不用|不想|别给|别要|除了|嫌|太贵|(?<!不)超过|(?<!不)高于|(?<!不)以上)[^，,。；;]{0,6}"
    r"([零一两二三四五六七八九\d]{1,6}[万千百]?|[0-9][0-9,]{2,6})")


def _neg_budget(s, user_text):
    """抽「被排除的金额」，并把误抽成预算的那个值清掉。

    只处理一种情况：这句话里既有「不要/如果超过」又有金额。
    此时金额不能当预算上限用 —— 要么去问，要么当排除线。
    """
    if not BUDGET_NEG.search(user_text):
        return None
    return {_cn_to_int(m.group(2)) or 0 for m in BUDGET_NEG.finditer(user_text)}


# 「要独显」不等于「要打游戏」。实测 2026-11-12 16:34：用户（AI 专业）说
# 「我想要带独立显卡的」，模型捏造 purpose=gaming，回答开头断言"你要打游戏"。
# 游戏词表：purpose 里的 gaming 必须能在原话里找到出处，找不到就剥掉。
GAMING_WORDS = ("游戏", "网游", "3A", "吃鸡", "原神", "steam", "Steam",
                "电竞", "黑神话", "永劫", "lol", "LOL", "FPS", "fps")


def guard_purpose(s, user_text):
    """用途字段必须能在用户原话里找到出处，找不到就剥掉（与 guard_budget 同哲学）。"""
    pl = s.get("purpose") or []
    if "gaming" in pl and not any(w in (user_text or "") for w in GAMING_WORDS):
        s["purpose"] = [p for p in pl if p != "gaming"]
        s["_gaming_stripped"] = True
    return s


def guard_budget(s, user_text):
    """预算必须能在用户原话里找到出处。找不到就置空，让它去问，而不是编一个。"""
    b = s.get("budget")
    nums = _budget_in_text(user_text)
    # 「不要七千的」：金额出现在否定语境里，不是预算上限。
    # 这里不清空所有金额 —— 只在这个预算是被否定的那个数时才丢。
    neg = _neg_budget(s, user_text) or set()
    if neg and b in neg:
        s["_budget_dropped"] = b
        s["_budget_negated"] = b
        s["budget"] = None
        return s
    # 「越便宜越好」：只在原话里确实没有金额时才算数
    if any(w in user_text for w in BUDGET_FREE) and not nums:
        s["budget"] = None
        s["_cheapest"] = True
        return s
    # 用户这轮给了明确金额，说明不再"看着办"了 -> 撤掉 _cheapest。
    # 不清的话，第一轮说过的"越便宜越好"会被 HARD_KEYS 继承到后面每一轮，
    # mode_of() 一直走 value 权重，用户后来给的预算只当过滤用、不当优先项。
    if nums and s.get("_cheapest"):
        s.pop("_cheapest", None)
    # 「太贵了，便宜点」——预算上限不变，但这轮按价格优先排。
    # 这是"在预算内找更便宜的"，不是"没有预算"。
    if any(w in user_text for w in BUDGET_LOWER):
        s.pop("_cheapest", None)
        s["_cheaper"] = True
    # 🔴 原话里一个金额都没有，模型却给了预算 —— 只能是编的。
    #   guard_budget 只在 extract_slots 的新鲜槽位上调用（跨轮继承合并不走
    #   这里），所以此时 s 里的 budget 只可能来自本轮原话；原话没金额还
    #   给预算，就是「6000mAh → budget=6000」那类规格数字污染的变形。
    if not nums:
        if b is not None:
            s["_budget_dropped"] = b
            s["budget"] = None
        return s
    if b is None:
        # 🔴 「预算七千，最多不超过八千」——模型有时不抽中文金额（实测
        #   2026-11-12 返回 budget=None）。预算词后面紧跟的金额就是预算，
        #   这里按规则兜底抽一次，且必须是 _budget_in_text 能追溯到的数。
        if re.search(r"预算|花费|控制在", user_text):
            m = re.search(
                r"(?:预算|花费|控制在)[^0-9零一二三四五六七八九]{0,4}"
                r"([0-9][0-9,]{2,6}|[零一两二三四五六七八九]{1,3}[万千百][零一两二三四五六七八九千百\d]{0,3})",
                user_text)
            if m:
                raw = m.group(1).replace(",", "")
                v = int(raw) if raw.isdigit() else _cn_to_int(raw)
                if v and 500 <= v <= 200000 and v in nums:
                    s["budget"] = v
                    return s
        return s
    if b not in nums:
        s["_budget_dropped"] = b
        s["budget"] = None
    return s


