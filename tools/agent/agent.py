# 模型的枚举污染：实测把「学设计」写成 cat="design"，
# 于是品类校验失败，用户看到"品类不在覆盖范围"这种莫名其妙的回答。
# 枚举字段必须白名单，不许模型发明。
VALID_CAT = {"thin", "gaming", "desktop", "upgrade"}
VALID_PURPOSE = {"office", "gaming", "dev", "video", "design"}

# 硬约束（过滤条件，不是权重）。这些键跨轮必须继承，
# 否则「不要封装内存」「要 32G」「不要荣耀」会在下一轮悄悄失效。
# 新增硬约束时加到这里，不要再去写单点 if。
HARD_KEYS = ("_minUpgrade", "_minRam", "_excludeBrand", "_cheapest", "_wantDgpu")


def normalize_slots(s):
    """把模型抽出来的槽位收敛到合法枚举。不合法的值降级处理，不要让它污染内核。"""
    cat = s.get("cat")
    if cat is not None and cat not in VALID_CAT:
        # 常见污染：cat 里写了用途词（design/game/office/study）
        low = str(cat).lower()
        if low in VALID_PURPOSE or low in ("study", "game", "work"):
            m = {"game": "gaming", "study": "office", "work": "office"}
            mapped = m.get(low, low)
            if mapped in VALID_PURPOSE:
                pl = s.get("purpose") or []
                if mapped not in pl:
                    pl.append(mapped)
                s["purpose"] = pl
        # 品类本身丢弃 → 让它缺，走追问，而不是报"不在覆盖范围"
        s["cat"] = None
        s["_cat_bypass"] = cat

    pl = s.get("purpose") or []
    if isinstance(pl, str):
        pl = [pl]
    s["purpose"] = [x for x in pl if x in VALID_PURPOSE]

    # 数字字段类型收敛
    for k in ("budget", "years", "dormWatt"):
        v = s.get(k)
        if isinstance(v, str):
            digits = re.sub(r"[^\d]", "", v)
            s[k] = int(digits) if digits else None
        elif isinstance(v, float):
            s[k] = int(v)
    return s


# 用户原话里根本没出现的预算数字 = 模型幻觉。
# 实测 2026-11-11：「轻薄本，越便宜越好」被抽成 budget=500，
