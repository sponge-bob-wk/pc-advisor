# -*- coding: utf-8 -*-
"""第九轮：指名问型号（match_named_model）+ 介绍分支（_intro_model）

为什么单独测这一块（2026-11-11 演示前）：
    U「华为MateBook D16怎么样」
    A「是笔记本还是台式？大概想放在宿舍用…」   ← 用户已指名道姓，系统还在问品类

这个函数前后改了 7 版，前 6 版全是"切词"思路（把机型名拆成 token 再比），
切出来的东西没有一个是对的：
    Redmi Book Pro 14 → ['14']           品牌被当泛词剥掉，只剩个 14
    DDR5 16G 单条     → [..., '516']     数字连读切出无意义的 516
    惠普战 66         → ['八代锐龙版']    66 被当"纯数字泛词"丢了，这台永远认不出
最终改成**别名法**：不拆原串，枚举"用户可能怎么称呼它"，每个别名都是完整子串。

本文件的重点不是"能认出几台"，而是**代价不对称的两侧都要测**：
  · 该认出的没认出 → 用户被反问品类（烦，但补一句还能救）
  · 不该认出的认了 → 用户问 A、系统答 B（严重，等于答非所问）
⇒ 第二节（必须 None）每一条都是硬门槛。
"""
import sys
sys.path.insert(0, ".")

import agent
import core

PASS = FAIL = 0
FAILS = []


def ck(name, ok, detail=""):
    global PASS, FAIL
    if ok:
        PASS += 1
        print("  [OK ] " + name)
    else:
        FAIL += 1
        FAILS.append(name + (" | " + detail if detail else ""))
        print("  [FAIL] " + name + ("   ← " + detail if detail else ""))


def hit(q):
    o = agent.match_named_model(q)
    return o["name"] if o else None


D = core.load()
NAMES = [o["name"] for o in D["offers"] if o.get("cat") in core.ALLOWED_CATS]


def bar(t):
    print()
    print("=" * 66)
    print(t)
    print("=" * 66)


# ==================================================================
bar("一、该认出的必须认出（说法变体）")
# 用户不会照着库里的名字打字。空格、大小写、中英混写、带不带型号后缀，
# 都得认出来 —— 否则就会出现「用户指名道姓，系统反问品类」。
# ==================================================================
CASES = [
    ("华为MateBook D16怎么样", "华为 MateBook D16"),
    ("matebookd16怎么样", "华为 MateBook D16"),
    ("MateBook D16", "华为 MateBook D16"),
    ("华为matebook d16 这个怎么样", "华为 MateBook D16"),
    ("联想小新16如何", "联想小新 16"),
    ("小新 Air15 怎么样", "联想小新 Air15 2026"),
    ("小新Air15", "联想小新 Air15 2026"),
    ("小新Air14柔光版", "联想小新 Air14 柔光版"),
    ("Redmi Book Pro 14 好吗", "Redmi Book Pro 14"),
    ("天选7怎么样", "华硕天选 7"),
    ("天选6怎么样", "天选6 2026（锐龙7 H260/RTX5050/32G/1T）"),
    ("拯救者Y7000P怎么样", "拯救者 Y7000P 2026"),
    ("华硕天选7", "华硕天选 7"),
    ("机械革命无界14X", "机械革命 无界 14X"),
    ("无界14x怎么样", "机械革命 无界 14X"),
    ("隐星P16怎么样", "隐星 P16 Pro"),
    ("戴尔灵越15怎么样", "戴尔灵越 15 2026"),
    ("惠普战66怎么样", "惠普战 66 八代锐龙版"),
    ("荣耀X14怎么样", "荣耀 X14 战斗版 2026"),
    # 🔴 2026-11-12 改：原来是 "暗影精灵 Pro 15"。
    #   那时池里只有 Pro 15 一台暗影精灵，所以"认成它"看似合理。
    #   v0.4 并池后暗影精灵有 3 台（11 酷睿 / 11 锐龙 / Pro 15），
    #   用户只说系列名 → 认成任何一台都是"答了另一台"，必须弃权反问。
    #   这条已经从「该认对的」挪到下面 NEG 里。
    ("耀世18怎么样", "机械革命 耀世 18 Pro"),
    # 🔴 2026-11-12 改：原来期望 "机械革命 苍龙 18 Pro"。
    #   现在池里有**两条**苍龙 18：RTX 5070（人工层 ¥12124）和
    #   RTX 5060（采集层 ¥10899），是两台不同机器（差 1225 元）。
    #   用户只说"苍龙18"没说哪版 → 弃权才对，不能替他选一版。
    #   已挪到 NEG 里。
    ("极光X怎么样", "机械革命 极光 X"),
    ("无畏16se怎么样", "华硕无畏 16SE 2026"),
    ("DDR5 32G套条多少钱", "DDR5 32G 套条"),
]
for q, want in CASES:
    got = hit(q)
    ck("%-28s → %s" % (q, want), got == want, "实际 %s" % got)


# ==================================================================
bar("二、不许认错的（这一节每条都是硬门槛）")
# 认错 = 用户问 A、系统答 B。比 MISS 严重得多，因为用户会以为系统在胡说。
# ==================================================================
NEG = [
    # 库里没有的型号 —— 必须弃权，让它走正常澄清流程
    ("ThinkBook 14 怎么样", "库里没有 ThinkBook，不能凑成 Redmi Book Pro 14"),
    ("XPS 13 怎么样", "库里没有 XPS"),
    # 🔴 2026-11-12 改：v0.4 并池后采集层**有**拯救者 Y7000P 2026。
    #   原来这条期望"库里没有拯救者"，是 22 台时代的结论。
    #   现在认出来是对的 —— 池里确实有这台，认不出才是新 bug。
    #   已挪到上面「该认对的」里。
    ("小米笔记本怎么样", "小米只在手机数据里有"),
    ("苹果笔记本怎么样", "苹果电脑不在覆盖范围"),
    # 🔴 2026-11-12 新增：系列名有多台时，必须弃权反问，不能挑一台答
    ("暗影精灵怎么样", "暗影精灵有 11 酷睿 / 11 锐龙 / Pro 15 三台，只报系列名"),
    ("苍龙18怎么样", "苍龙 18 有 RTX5070 和 RTX5060 两版，差 1225 元"),
    ("小新怎么样", "小新有十几台"),
    ("天选怎么样", "天选有 7/6/Air/Pro 多台"),
    # 只提品牌不提型号 —— 品牌是加分项，不是特征
    ("华为怎么样", "只提品牌"),
    ("联想怎么样", "只提品牌"),
    ("戴尔怎么样", "只提品牌"),
    ("华硕怎么样", "只提品牌"),
    # 泛指
    ("有什么推荐", "没指任何机型"),
    ("学设计买什么", "没指任何机型"),
    ("预算5000推荐一台", "没指任何机型"),
    ("我想买个游戏本", "说的是品类"),
    ("这个机器怎么样", "指代词不是型号"),
    # 代次对不上 —— 用户问 6 代，回答 7 代就是答非所问
    # 🔴 2026-11-12 改：v0.4 并池后采集层**有**天选6 2026，认出来是对的。
    #   原来这条写"库里只有天选 7"，是 22 台时代的结论。
    #   代次判据本身仍然有效 —— 见下面「暗影精灵10」那条（库里确实只有 11 代）。
    ("暗影精灵10怎么样", "库里只有暗影精灵 11 和 Pro 15，没有 10 代"),
    ("小新17怎么样", "库里没有 17 寸小新"),
    # 系列名不够 —— 两台都叫"小新"，分不清就弃权
    ("小新怎么样", "小新有两款，分不清是哪台"),
]
for q, why in NEG:
    got = hit(q)
    ck("%-24s 弃权（%s）" % (q, why), got is None, "实际认成 %s" % got)


# ==================================================================
bar("三、别名生成的分辨力")
# 别名法最容易出的两个错：品牌名本身进了别名、泛词进了别名。
# 这两类都会让"只提品牌"变成"认出了具体型号"。
# ==================================================================
for o in D["offers"]:
    if o.get("cat") not in core.ALLOWED_CATS:
        continue
    al = agent._model_aliases(o.get("name"), o.get("brand"))
    brand_n = agent._norm(o.get("brand"))
    ck("%-22s 别名里没有品牌名本身" % o["name"], brand_n not in al, str(al))
    ck("%-22s 别名里没有纯泛词" % o["name"],
       not [a for a in al if a in agent.GENERIC_TOKENS], str(al))
    ck("%-22s 别名里没有年份" % o["name"],
       not [a for a in al if a.startswith("20") and a[2:].isdigit()], str(al))

# 惠普战 66 是"中文+数字粘连"的典型：切词版会把它切成 ['八代锐龙版']，
# 66 丢掉，这台永远认不出。别名法必须保住「战66」。
wp = [o for o in D["offers"] if o["name"].startswith("惠普战")]
if wp:
    al = agent._model_aliases(wp[0]["name"], wp[0]["brand"])
    ck("惠普战 66 保住了「战66」这个别名（中文+数字粘连）",
       "战66" in al, str(al))


# ==================================================================
bar("四、接入主流程：指名问型号不能走成反问品类")
# 这一节测的是 run()。函数写完了但没接上，测试全绿也不代表实际能用。
# ==================================================================
r = agent.run("华为MateBook D16怎么样")
ck("指名问型号 → stage 不是 clarify", r.get("stage") != "clarify", r.get("stage"))
ck("指名问型号 → focus 切到那台",
   r.get("focusName") == "华为 MateBook D16", str(r.get("focusName")))
ck("指名问型号 → reason 标注清楚", "指名" in (r.get("reason") or ""), str(r.get("reason")))
ck("指名问型号 → 回答里没反问「笔记本还是台式」",
   "笔记本还是台式" not in (r.get("reply") or ""), (r.get("reply") or "")[:60])

r2 = agent.run("联想小新16如何")
ck("没提用途时 → 先介绍这台，不是「数据不足」",
   "数据不足" not in (r2.get("reply") or "")
   and "没能" not in (r2.get("reply") or ""), (r2.get("reply") or "")[:80])
ck("没提用途时 → 最后要问用途",
   any(w in (r2.get("reply") or "") for w in ["干什么", "什么用途", "拿来"]),
   (r2.get("reply") or "")[-60:])

# 已经说过用途时，指名问型号应该直接判匹配度，不重复介绍
r3 = agent.run("Redmi Book Pro 14 怎么样", known={"cat": "thin", "budget": 6000,
                                              "purpose": ["design"]})
ck("已知用途 + 指名 → 走匹配度判断（fit）",
   r3.get("stage") == "fit", r3.get("stage"))
ck("已知用途 + 指名 → focus 是那台",
   r3.get("focusName") == "Redmi Book Pro 14", str(r3.get("focusName")))

# 库里没有的型号仍要走正常澄清，不能硬凑
r4 = agent.run("ThinkBook 14 怎么样")
ck("库里没有的型号 → 不被硬凑成别的机器",
   r4.get("focusName") not in NAMES[:1] or r4.get("reason") is None,
   str(r4.get("focusName")))


# ==================================================================
bar("五、caution 里的别的型号不能说出去")
# 实测：小新 16 的 caution 原文是「小新 16SE 有双 M.2 硬盘位，同价位更值得看」
# 这句放在这条数据的字段里，但说的是**另一台**。模型照抄后，
# 用户问「小新16怎么样」，回答里在安利 16SE。
# ==================================================================
xx = [o for o in D["offers"] if o["name"] == "联想小新 16"]
if xx:
    cleaned = agent._clean_caution(xx[0]["caution"], xx[0])
    ck("小新 16 的 caution 被过滤（讲的是 16SE）",
       "16SE" not in cleaned and "更值得" not in cleaned, repr(cleaned))

# 反过来：规格代号不能误删。LPDDR5 / RTX 5050 / DDR4 这些是**本机配置**，
# 被当成"别的型号"删掉就等于把有效信息扔了。
KEEP = ["华硕无畏 16SE 2026", "华硕天选 7", "只换板 U：9800X3D + B850M",
        "旧机加内存 / 换固态（不换整机）"]
for nm in KEEP:
    o = [x for x in D["offers"] if x["name"] == nm]
    if not o:
        continue
    raw = o[0]["caution"]
    cl = agent._clean_caution(raw, o[0])
    # 允许标点被规整，但实质内容不能少
    ck("%-24s 的 caution 不被误删（规格代号不是型号）" % nm,
       len(cl) >= len(raw) * 0.6, "%r → %r" % (raw, cl))


# ==================================================================
bar("总账")
print()
print("=" * 66)
print("通过 %d / %d" % (PASS, PASS + FAIL))
if FAILS:
    print("\n失败项：")
    for f in FAILS:
        print("  · " + f)
else:
    print("全绿。")
print("=" * 66)
sys.exit(1 if FAIL else 0)