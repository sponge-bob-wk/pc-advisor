# -*- coding: utf-8 -*-
"""fix_unknown_quality.py —— unknown 扩充质量修正

## 问题

程序化组合产出「嗯那个」「嗯在吗」「嗯。这个」这类**不自然**的句子。
真实用户不会这么说话，喂给模型只会学到噪声。

## 什么才是真 unknown

按实际对话日志统计，unknown 主要是：

① **纯语气词**（单个）：嗯 / 哦 / 啊 / 呃
② **打招呼**：在吗 / 你好 / hi
③ **明确说不知道**：不知道买啥 / 没想好 / 随便
④ **跑题**：今天天气不错 / 你是谁
⑤ **泛泛要求**：推荐一下 / 介绍下（没给任何条件）

注意 ③④⑤ 才是重点 —— 它们有实际文字，但都不构成选购需求。
而 ① 简单，模型很容易学。

所以扩的重点是 ③④⑤，不是堆语气词组合。

## 判据边界

「推荐一下」为什么是 unknown？
  因为它没说要推荐什么条件（预算？用途？品类？）
  对比：「推荐一台五千的游戏本」→ state_new_need

「随便看看」为什么不是 refuse_switch？
  因为它不针对当前这台（可能是第一句）
  对比：「这个不行，再看看」→ refuse_switch

## 重写策略

① 保留自然的语气词（单字，不组合）
② 重点扩充「泛泛要求」的变体 —— 这是模型最容易错的
③ 每个都写明判据
"""
import io
import json
import random
import sys

sys.stdout.reconfigure(encoding="utf-8")

OUT = r"E:\电脑涨价分析\tools\agent\lora_data\unknown-expand.jsonl"

S = []


def a(u, cot):
    S.append((u, cot))


# ══════════════════════════════════════════════════════════════════
# ① 纯语气词（单个，自然）
# ══════════════════════════════════════════════════════════════════
for u in ["嗯", "哦", "啊", "呃", "唔", "哈", "诶", "哎", "噢",
          "嗯嗯", "哦哦", "啊啊", "额", "emmm", "emm"]:
    a(u, "「%s」只有语气，没有任何选购信息 → unknown" % u)

# ══════════════════════════════════════════════════════════════════
# ② 打招呼
# ══════════════════════════════════════════════════════════════════
for u in ["在吗", "在不在", "你好", "您好", "hi", "hello", "有人吗",
          "在不在呀", "你好呀", "在嘛"]:
    a(u, "「%s」是打招呼，还没提需求 → unknown" % u)

# ══════════════════════════════════════════════════════════════════
# ③ 明确说不知道（有文字但不构成条件）
# ══════════════════════════════════════════════════════════════════
dunno = [
    "不知道买啥", "不知道选什么", "不知道买哪个", "没想好",
    "还没想好", "不太清楚", "不清楚", "没概念", "没头绪",
    "不确定", "说不上来", "不知道从哪开始", "有点纠结",
    "选择困难", "纠结中", "不知道要什么样的", "没主意",
    "你帮我定", "你说了算", "你看着办", "帮我选",
    "都行", "随便", "看你", "听你的", "你推荐吧",
    "随便来一个", "随便推荐一个", "随便买一个",
    "先随便看看", "随便逛逛",
]
for u in dunno:
    a(u, "「%s」表示用户自己还没想好，没给出任何条件 → unknown" % u)

# ══════════════════════════════════════════════════════════════════
# ④ 跑题（不是选购问题）
# ══════════════════════════════════════════════════════════════════
offtopic = [
    "今天天气不错", "你是谁", "你能干什么", "你会什么", "你是AI吗",
    "你是机器人吗", "你几岁了", "吃了吗", "几点了", "帮我想个名字",
    "写首诗", "讲个笑话", "翻译一下", "你聪明吗", "你喜欢什么",
    "你住哪", "在干嘛", "无聊", "陪我聊天", "你会写代码吗",
    "怎么学英语", "推荐个电影", "哪家外卖好吃",
]
for u in offtopic:
    a(u, "「%s」跟挑电脑无关，跑题了 → unknown" % u)

# ══════════════════════════════════════════════════════════════════
# ⑤ 泛泛要求（没给任何具体条件的"推荐"）—— 这是重点
# ══════════════════════════════════════════════════════════════════
vague = [
    "推荐一下", "推荐一个", "推荐个呗", "给我推荐", "帮忙推荐",
    "介绍一下", "介绍下", "说说看", "讲讲", "讲讲看",
    "看看", "我看看", "给我看看", "有什么", "有什么推荐",
    "有什么好东西", "有什么好推荐", "有哪些", "来一个",
    "来点建议", "给点建议", "有什么建议", "怎么选",
    "我该买什么", "买什么好", "哪个好", "什么牌子好",
    "哪个牌子", "有什么选择", "能选什么",
    "列一下", "讲一下", "帮我看看", "瞧瞧", "瞅瞅",
    "推荐几个", "推荐几款", "来几款", "多推荐几个",
]
for u in vague:
    a(u, "「%s」是泛泛地要推荐，但没说预算/用途/品类任何一项 → unknown"
         "（对比：'推荐一台五千的游戏本' 才是 state_new_need）" % u)

# ══════════════════════════════════════════════════════════════════
# ⑥ 只有标点
# ══════════════════════════════════════════════════════════════════
for u in ["？", "？？", "。", "。。。", "……", "??", "!!", "。。。？"]:
    a(u, "只有标点符号，没有内容 → unknown")


def main():
    rnd = random.Random(20261134)
    print("=" * 74)
    print("unknown 类扩充（质量修正版）")
    print("=" * 74)
    print()

    # 去重
    seen = set()
    uniq = []
    for u, c in S:
        if u in seen:
            continue
        seen.add(u)
        uniq.append((u, c))

    rows = []
    for u, c in uniq:
        gold = {"intent": "unknown", "topic": "none", "fit": False}
        js = json.dumps(gold, ensure_ascii=False)
        content = ("%s。\n%s" % (c, js)) if rnd.random() < 0.55 else js
        rows.append({
            "messages": [
                {"role": "user", "content": u},
                {"role": "assistant", "content": content},
            ],
            "_meta": {"src": "unknown-expand"},
        })

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print("  分类:")
    print("    语气词      %d" % 15)
    print("    打招呼      %d" % 10)
    print("    说不知道    %d" % len(dunno))
    print("    跑题        %d" % len(offtopic))
    print("    泛泛要求    %d" % len(vague))
    print("    只有标点    %d" % 8)
    print()
    print("  合计 %d 条（去重后）" % len(rows))
    print("  写出 %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
