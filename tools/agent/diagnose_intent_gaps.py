def main():
    print("=" * 78)
    print("意图分类缺口诊断")
    print("=" * 78)
    print("  测试集 %d 条" % len(CASES))
    print()

    # 按意图统计
    from collections import Counter, defaultdict
    by_intent = Counter(e for _, e, _ in CASES)
    print("  分布：")
    for k, v in by_intent.most_common():
        print("    %-16s %3d 条" % (k, v))
    print()

    # 跑
    results = []
    for s, exp, note in CASES:
        il._CACHE.clear()
        try:
            r = il.route(s, focus=FOCUS)
            got = r.get("intent")
            why = r.get("why", "")
        except Exception as e:
            got, why = "ERR", str(e)[:30]
        results.append((s, exp, got, note, why))

    ok = sum(1 for _, e, g, _, _ in results if e == g)
    print("=" * 78)
    print("结果：%d/%d = %.1f%%" % (ok, len(results), 100.0 * ok / len(results)))
    print("=" * 78)

    # 按意图统计准确率
    print()
    print("  各意图准确率：")
    stat = defaultdict(lambda: [0, 0])
    for s, e, g, n, w in results:
        stat[e][1] += 1
        if e == g:
            stat[e][0] += 1
    for k in sorted(stat, key=lambda x: -stat[x][1]):
        c, t = stat[k]
        bar = "█" * int(20.0 * c / t) + "░" * (20 - int(20.0 * c / t))
        print("    %-16s %3d/%-3d %5.1f%%  %s" % (k, c, t, 100.0 * c / t, bar))

    # 错误明细
    bad = [(s, e, g, n) for s, e, g, n, w in results if e != g]
    print()
    print("  判错 %d 条：" % len(bad))
    # 按 (期望→实际) 归类
    grp = defaultdict(list)
    for s, e, g, n in bad:
        grp[(e, g)].append((s, n))
    for (e, g), items in sorted(grp.items(), key=lambda x: -len(x[1])):
        print()
        print("    %s → %s（%d 条）" % (e, g, len(items)))
        for s, n in items[:8]:
            print("        %-34s [%s]" % (s[:32], n))

    # 导出
    out = r"E:\电脑涨价分析\tools\agent\lora_data\adversarial-intent.jsonl"
    io.open(out, "w", encoding="utf-8", newline="\n").write(
        "\n".join(json.dumps({"text": s, "expect": e, "note": n,
                              "got": g, "ok": e == g},
                             ensure_ascii=False) for s, e, g, n, w in results) + "\n")
    print()
    print("  明细已写入 %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
